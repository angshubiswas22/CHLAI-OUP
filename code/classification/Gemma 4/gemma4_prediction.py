import os
import time
import pandas as pd
from openai import OpenAI
from dotenv import load_dotenv
import json
import re

load_dotenv()
key = os.environ.get("OPENROUTER_API_KEY")

if not key:
    print("CRITICAL ERROR: I cannot find the OpenRouter key. Check your .env file!")
    exit()

print("Key loaded! Connecting to OpenRouter for AI Detection...")


client = OpenAI(
    base_url="https://openrouter.ai/api/v1",
    api_key=key,
)

def extract_json_from_text(text):
    """Finds and parses JSON data even if the model adds conversational text around it."""
    try:
        match = re.search(r'\{.*\}', text, re.DOTALL)
        if match:
            return json.loads(match.group(0))
        return None
    except json.JSONDecodeError:
        return None

def run_ai_detection():
    input_csv = "" 
    output_csv = "Detection_Output_Gemma.csv"
    

    if os.path.exists(output_csv):
        print(f"Found existing progress! Resuming from '{output_csv}'...")
        df = pd.read_csv(output_csv)
    else:
        print(f"Starting fresh. Loading '{input_csv}'...")
        try:
            df = pd.read_csv(input_csv)
        except FileNotFoundError:
            print(f"Error: Could not find '{input_csv}'.")
            return
        
        df['Detection_Label'] = ""
        df['Confidence_Score'] = ""
        df['Reasoning'] = ""
        df['Processed'] = False
        
  
        df['Poem_Clarity'] = ""
        df['Literary_Devices'] = ""
        df['Punctuation_Spacing'] = ""
        df['Grammar_Spelling'] = ""
        df['Originality'] = ""

    df['Processed'] = df['Processed'].astype(str).str.upper() == 'TRUE'

    columns_to_object = ['Detection_Label', 'Confidence_Score', 'Reasoning', 
                         'Poem_Clarity', 'Literary_Devices', 'Punctuation_Spacing', 
                         'Grammar_Spelling', 'Originality']
    
    for col in columns_to_object:
        if col in df.columns:
            df[col] = df[col].astype(object)

    print(f"Total rows left to process: {len(df[df['Processed'] != True])}")
    print("Starting Upgraded Detection via Gemma 4 ...\n")

    system_prompt = (
        "You are an expert AI text detector and literary analyst. "
        "Analyze the provided poem and determine if it was written by a Human or generated by AI.\n\n"
        "As part of your analysis, evaluate the likelihood of AI involvement for each of the 5 criteria below. "
        "Use this exact Likert scale for each criterion to reflect your judgment: "
        "'Highly Likely', 'Likely', 'Unsure', 'Unlikely', 'Highly Unlikely'.\n\n"
        "Criteria Context:\n"
        "1. Poem Clarity: Evaluate whether the language aligns with the overall mood and tone of the writing.\n"
        "2. Literary Devices: Evaluate the depth, execution, and emotive value of the literary devices and metaphors used.\n"
        "3. Punctuation and Spacing: Evaluate whether the structured or unstructured form and spacing carry intentional, deeper meaning.\n"
        "4. Grammar and Spelling: Evaluate the standard of the grammar, mechanics, and spelling.\n"
        "5. Originality: Evaluate whether the poem shows signs of being plagiarized or heavily derived from another source.\n\n"
        "You MUST respond with ONLY a valid JSON object. Do not include any conversational text or markdown code blocks.\n"
        "Use this exact structure:\n"
        "{\n"
        '  "label": "Human" or "AI",\n'
        '  "confidence": <integer from 0 to 100>,\n'
        '  "poem_clarity": "<Likert value>",\n'
        '  "literary_devices": "<Likert value>",\n'
        '  "punctuation_spacing": "<Likert value>",\n'
        '  "grammar_spelling": "<Likert value>",\n'
        '  "originality": "<Likert value>",\n'
        '  "reasoning": "<1 to 2 sentences explaining which of the 5 criteria was the KEY factor in your decision. If the key factor was NOT from these 5, explicitly state the new factor.>"\n'
        "}"
    )

    try:
        for index, row in df.iterrows():
            if row['Processed'] == True:
                continue

            poem_text = row['poem'] 

            if pd.isna(poem_text) or str(poem_text).strip() == "":
                print(f"Row {index}: Empty poem text found. Skipping...")
                df.at[index, 'Processed'] = True
                continue

            user_prompt = f"Please classify the following poem:\n\n{poem_text}"

            success = False
            while not success:
                try:
                    # Make the API Call (500 tokens is still plenty for this expanded JSON)
                    response = client.chat.completions.create(
                        model="google/gemma-4-31b-it", 
                        temperature=0.0,   
                        max_tokens=500,
                        messages=[
                            {"role": "system", "content": system_prompt},
                            {"role": "user", "content": user_prompt}
                        ]
                    )

                    message_obj = response.choices[0].message
                    raw_content = getattr(message_obj, 'content', None)

                    if raw_content:
                        parsed_data = extract_json_from_text(raw_content)
                        
                        if parsed_data:
                            # 1. Base Variables
                            label = str(parsed_data.get("label", "ERROR"))
                            confidence_score = str(parsed_data.get("confidence", "ERROR"))
                            reasoning = str(parsed_data.get("reasoning", "ERROR"))
                            

                            clarity = str(parsed_data.get("poem_clarity", "ERROR"))
                            devices = str(parsed_data.get("literary_devices", "ERROR"))
                            punct = str(parsed_data.get("punctuation_spacing", "ERROR"))
                            grammar = str(parsed_data.get("grammar_spelling", "ERROR"))
                            originality = str(parsed_data.get("originality", "ERROR"))


                            df.at[index, 'Detection_Label'] = label
                            df.at[index, 'Confidence_Score'] = confidence_score
                            df.at[index, 'Reasoning'] = reasoning
                            
                            df.at[index, 'Poem_Clarity'] = clarity
                            df.at[index, 'Literary_Devices'] = devices
                            df.at[index, 'Punctuation_Spacing'] = punct
                            df.at[index, 'Grammar_Spelling'] = grammar
                            df.at[index, 'Originality'] = originality
                            
                            df.at[index, 'Processed'] = True
                            
                            print(f"Row {index} | Label: {label} ({confidence_score}%)")
                            print(f"Key Factor Reasoning: {reasoning}\n" + "-"*40)
                        else:
                            print(f"Row {index} | FORMAT ERROR: Could not extract clean JSON.")
                            df.at[index, 'Reasoning'] = f"RAW OUTPUT: {raw_content.strip()}"
                            df.at[index, 'Processed'] = True 
                    else:
                        print(f"Row {index} | ERROR: Received empty response.")
                        df.at[index, 'Reasoning'] = "ERROR: Empty Response"
                        df.at[index, 'Processed'] = True


                    df.to_csv(output_csv, index=False)
                    success = True  
                    time.sleep(2)

                except Exception as e:
                    print(f"\nAPI/Network Error on Row {index}: {e}")
                    print("Pausing for 60 seconds before retrying this row...")
                    time.sleep(60)

        print(f"\nDone! All rows processed successfully. Final dataset saved to '{output_csv}'")

    except KeyboardInterrupt:
        print("\n\n[Ctrl+C Detected] Safely stopping pipeline... Exporting checkpoint snapshot to disk.")
        df.to_csv(output_csv, index=False)
        print("Progress saved cleanly. You can run this file again later to resume.")
        exit()

if __name__ == "__main__":
    run_ai_detection()